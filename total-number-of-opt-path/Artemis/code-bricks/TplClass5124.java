public class TplClass5124 {

    private static final void method(byte[] bb, byte[] bytes) throws Throwable {
        boolean diff = false;
        // to getBytes().
        for (int i = 0; i < bytes.length; i++) {
            if (bytes[i] != bb[i])
                diff = true;
        }
        if (!diff)
            ;
    }
}

